import {readFileSync, writeFileSync, readdirSync} from 'node:fs'
import {join} from 'node:path'
const SRC = 'hypermedia'
const OUT = 'frontend/packages/ui/src/onyx/onyx-schemas.generated.ts'
const files = readdirSync(SRC).filter((f) => f.endsWith('.schema.json'))
const schemas = {}
for (const f of files.sort()) {
  const name = f.replace(/\.schema\.json$/, '')
  schemas[name] = JSON.parse(readFileSync(join(SRC, f), 'utf8'))
}
// A schema carries no name of its own; its page does. Bundle each page's name and
// summary so pills and labels can name a bundled schema without a fetch.
const pages = {}
for (const f of files.sort()) {
  const name = f.replace(/\.schema\.json$/, '')
  let md
  try {
    md = readFileSync(join(SRC, `${name}.md`), 'utf8')
  } catch {
    continue
  }
  const fm = /^---\n([\s\S]*?)\n---/.exec(md)
  if (!fm) continue
  const page = {}
  for (const line of fm[1].split('\n')) {
    const kv = /^(name|summary):\s*(.*)$/.exec(line)
    if (!kv) continue
    let v = kv[2].trim()
    if (/^".*"$/.test(v)) {
      try {
        v = JSON.parse(v)
      } catch {}
    }
    page[kv[1]] = v
  }
  if (page.name) pages[name] = page
}
const lock = JSON.parse(readFileSync(join(SRC, 'schemas.lock.json'), 'utf8'))
const manifest = lock.schemas || {}
const header = `// AUTO-GENERATED by scripts/gen-onyx (do not edit by hand).
// The Onyx reference schemas (hypermedia/*.schema.json) bundled for in-app browsing +
// validation, plus the published CID manifest (schemas.lock.json).
// Regenerate: node scripts/gen-onyx.mjs\n\n`
// Each export is a single-line JSON literal; `prettier-ignore` keeps the
// bundle compact instead of exploding 150KB of schemas across thousands of lines.
const body =
  `// prettier-ignore\nexport const ONYX_AUTHORITY: ReadonlyArray<readonly [string, string]> = ${JSON.stringify([['onyx-', 'hyper.media'], ['hypermedia-', 'seed.hyper.media'], ['seed-', 'seed.hyper.media'], ['example-', 'example.com']])} as const\n\n` +
  `// prettier-ignore\nexport const ONYX_MANIFEST: Record<string, string> = ${JSON.stringify(manifest, null, 0)}\n\n` +
  `/** filename (no .schema.json) -> the name and summary of the page that defines it. */\n` +
  `// prettier-ignore\nexport const ONYX_PAGES: Record<string, {name: string; summary?: string}> = ${JSON.stringify(pages)}\n\n` +
  `/** filename (no .schema.json) -> schema object, e.g. "onyx-map-schema", "example-person", "hypermedia-change". */\n` +
  `// prettier-ignore\nexport const ONYX_SCHEMAS: Record<string, any> = ${JSON.stringify(schemas)}\n`
writeFileSync(OUT, header + body)
console.log(`wrote ${OUT}: ${Object.keys(schemas).length} schemas, ${Object.keys(manifest).length} manifest entries`)
