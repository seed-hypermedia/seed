import {expect, test} from '@playwright/test'

test('typed parameters apply to the URL, survive reload, and track browser history', async ({page}, testInfo) => {
  await page.goto('/parameters.html?p.name=%22Initial%22&p.age=3&v=revision#block')
  await page.getByRole('button', {name: 'Page parameters', exact: true}).click()
  const dialog = page.getByRole('dialog', {name: 'Page parameters'})
  await expect(dialog.getByRole('textbox', {name: 'name', exact: true})).toHaveValue('Initial')
  await dialog.getByRole('textbox', {name: 'name', exact: true}).fill('Hello & 🪴')
  await dialog.getByRole('spinbutton', {name: 'age', exact: true}).fill('1.5')
  await expect(dialog.getByRole('button', {name: 'Apply', exact: true})).toBeDisabled()
  await dialog.getByRole('spinbutton', {name: 'age', exact: true}).fill('5')
  await dialog.getByRole('switch', {name: 'Include active', exact: true}).click()
  await dialog.getByRole('switch', {name: 'active', exact: true}).click()
  await page.screenshot({path: testInfo.outputPath('parameters-desktop.png')})
  await dialog.getByRole('button', {name: 'Apply', exact: true}).click()
  await expect(dialog).toBeHidden()
  await expect(page.getByTestId('page-input')).toHaveText(JSON.stringify({name: 'Hello & 🪴', age: 5, active: true}))
  const url = new URL(page.url())
  expect(url.searchParams.get('p.name')).toBe(JSON.stringify('Hello & 🪴'))
  expect(url.searchParams.get('v')).toBe('revision')
  expect(url.hash).toBe('#block')
  await page.reload()
  await expect(page.getByTestId('page-input')).toContainText('Hello & 🪴')
  await page.getByRole('button', {name: 'Page parameters', exact: true}).click()
  await page.goBack()
  await expect(dialog.getByRole('textbox', {name: 'name', exact: true})).toHaveValue('Initial')
  await page.goForward()
  await expect(dialog.getByRole('textbox', {name: 'name', exact: true})).toHaveValue('Hello & 🪴')
  await dialog.getByRole('textbox', {name: 'name', exact: true}).fill('Unapplied')
  await dialog.getByRole('button', {name: 'Cancel', exact: true}).click()
  await expect(page.getByTestId('page-input')).toContainText('Hello & 🪴')
})

test('parameter editor fits a phone viewport and supports keyboard dismissal', async ({page}, testInfo) => {
  await page.setViewportSize({width: 390, height: 844})
  await page.goto('/parameters.html?p.name=%22Ada%22&p.age=3&p.active=false')
  await page.getByRole('button', {name: 'Page parameters', exact: true}).click()
  const dialog = page.getByRole('dialog', {name: 'Page parameters'})
  await expect(dialog.getByRole('textbox', {name: 'name', exact: true})).toBeVisible()
  const box = await dialog.boundingBox()
  expect(box!.x).toBeGreaterThanOrEqual(0)
  expect(box!.width).toBeLessThanOrEqual(390)
  expect(box!.height).toBeLessThanOrEqual(844)
  await dialog.getByRole('button', {name: 'Apply', exact: true}).scrollIntoViewIfNeeded()
  await expect(dialog.getByRole('button', {name: 'Apply', exact: true})).toBeVisible()
  await page.screenshot({path: testInfo.outputPath('parameters-phone.png')})
  await page.keyboard.press('Escape')
  await expect(dialog).toBeHidden()
  await expect(page.getByRole('button', {name: 'Page parameters', exact: true})).toBeFocused()
})

test('opens from page options and restores keyboard focus after dismissal', async ({page}) => {
  await page.goto('/parameters.html?p.name=%22Ada%22')
  const trigger = page.getByRole('button', {name: 'Page options', exact: true})
  await trigger.click()
  await page.getByRole('menuitem', {name: 'Page parameters', exact: true}).click()
  const dialog = page.getByRole('dialog', {name: 'Page parameters'})
  await expect(dialog.getByRole('textbox', {name: 'name', exact: true})).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(dialog).toBeHidden()
  await expect(trigger).toBeFocused()
})
